import type { SourceDefinition } from "./types";

/**
 * Registry of live sources. Adding a source = adding one entry (and, for a new site layout, one
 * adapter). Rules we hold ourselves to:
 *  - only documented public APIs may set `respectRobots: false`;
 *  - every item links back to the original page and names the source;
 *  - `minIntervalMinutes` honours each provider's published rate guidance;
 *  - if a provider's terms forbid redistribution, it does not belong here.
 *
 * Everything here was exercised against the real sites from GitHub's own runners on 2026-10-11 (see the
 * "live probe" notes in the README). Two findings shaped the registry:
 *  - several `.gov.pk` sites (NJP, BE&OE, FPSC, PPSC, AJKPSC, HEC …) time out, fail TLS or answer 403 when
 *    called from a US datacenter. Those are tagged `network: "pk"` and are only fetched from a Pakistani
 *    connection (`npm run scrape:pk`); the rest of the pipeline never waits on them;
 *  - a few well-known aggregators block datacenter traffic outright. They are switched off with the reason
 *    written down, never retried with disguised requests.
 * The HTML sources (njp, beoe-notices, spsc, bpsc, etea) are marked `experimental`: the scheduled run says
 * `empty` or `error` on the status page the day a layout changes.
 */
/** Words that mark a post as something nobody can apply to (results, slips, syllabi, quizzes …). */
const PK_NOT_AN_OPENING = "result|roll no|slip|merit list|syllabus|past paper|answer key|admit card|date sheet|test date|quiz|mcqs|general knowledge|solved paper|interview schedule|final list|selection list";
const PK_OPENING = "jobs?\\b|vacanc|recruit|career|internship|traineeship|scholarship|admission|hiring|walk[- ]in|apply";

/**
 * Pakistani job aggregators that publish a WordPress REST API or RSS feed (checked from GitHub's servers on
 * 2026-10-11: robots.txt allows the feed, the site answers). They repost newspaper advertisements, so they
 * rank below the official portals and every card says so. Only the title, excerpt and link are used.
 */
function pkAggregator(spec: { id: string; name: string; homepage: string; endpoint: string; adapter?: "wordpress" | "rss"; maxItems?: number; maxAgeDays?: number; include?: string }): SourceDefinition {
  const host = new URL(spec.homepage).host.replace(/^www\./, "");
  return {
    id: spec.id,
    name: spec.name,
    homepage: spec.homepage,
    adapter: spec.adapter ?? "wordpress",
    endpoint: spec.endpoint,
    defaultKind: "job",
    scope: "pakistan",
    authority: 4,
    minIntervalMinutes: 180,
    maxItems: spec.maxItems ?? 30,
    enabled: true,
    resourceId: spec.id,
    attribution: `Listings via ${spec.name} (${host}) — an unofficial aggregator, not a government site`,
    terms: `Public ${spec.adapter === "rss" ? "RSS feed" : "WordPress REST API / RSS"}. Title, excerpt and link only; confirm every advertisement on the department's own site.`,
    params: { maxAgeDays: spec.maxAgeDays ?? 30, include: spec.include ?? PK_OPENING, exclude: PK_NOT_AN_OPENING },
  };
}

