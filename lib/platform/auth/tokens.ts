import { SignJWT, decodeProtectedHeader, errors as joseErrors, jwtVerify } from "jose";
import { randomUUID } from "node:crypto";
import { API_SCOPES, type ApiScope, type PlatformConfig } from "../config";
import { ApiError } from "../errors";

/**
 * Short-lived device access tokens (JWS, HS256) - the credential the Android app uses for the endpoints that cost
 * money or CPU (tools, assistant).
 *
 * Design decisions (docs/adr/0004-device-tokens.md):
 *  - `jose` does the cryptography and claim validation (audited, algorithm-pinned); nothing hand-rolled.
 *  - HS256 with rotating secrets (`kid` header): the first configured secret signs, all of them verify, so a
 *    rotation never logs the fleet out. Symmetric is fine because only this service issues *and* verifies.
 *  - The token identifies an install (`sub` = random install id), never a person. It carries no personal data.
 *  - Lifetime defaults to one hour; the app re-registers (cheap proof of work) instead of holding a refresh token,
 *    so there is no long-lived credential on the device to steal.
 */

export const TOKEN_ISSUER = "raahi";
export const TOKEN_AUDIENCE = "raahi-api";
const CLOCK_TOLERANCE_SECONDS = 30;

export interface DeviceClaims {
  /** Install id (UUID generated by the app). */
  sub: string;
  scopes: ApiScope[];
  platform: string;
  iat: number;
  exp: number;
  jti: string;
}

export interface IssuedToken {
  token: string;
  tokenType: "Bearer";
  expiresIn: number;
  scope: string;
}

const DEVICE_SCOPES: readonly ApiScope[] = ["read", "tools", "assistant"];

export async function issueDeviceToken(
  config: Pick<PlatformConfig, "tokenSecrets" | "tokenTtlSeconds">,
  input: { installId: string; platform: string },
  nowSeconds: number,
): Promise<IssuedToken> {
  const signer = config.tokenSecrets[0];
  if (!signer) throw new ApiError("not_configured", "Device registration is not enabled on this deployment.");
  const scope = DEVICE_SCOPES.join(" ");
  const token = await new SignJWT({ scope, pf: input.platform })
    .setProtectedHeader({ alg: "HS256", kid: signer.kid, typ: "JWT" })
    .setIssuer(TOKEN_ISSUER)
    .setAudience(TOKEN_AUDIENCE)
    .setSubject(input.installId)
    .setIssuedAt(nowSeconds)
    .setNotBefore(nowSeconds)
    .setExpirationTime(nowSeconds + config.tokenTtlSeconds)
    .setJti(randomUUID())
    .sign(signer.key);
  return { token, tokenType: "Bearer", expiresIn: config.tokenTtlSeconds, scope };
}

const unauthorised = (message: string, code: "unauthorized" | "token_expired" = "unauthorized") =>
  new ApiError(code, message, { headers: { "WWW-Authenticate": `Bearer realm="raahi", error="invalid_token"` } });

export async function verifyDeviceToken(config: Pick<PlatformConfig, "tokenSecrets">, token: string, nowSeconds: number): Promise<DeviceClaims> {
  if (config.tokenSecrets.length === 0) throw unauthorised("Device tokens are not accepted on this deployment.");
  let kid: string | undefined;
  try {
    kid = decodeProtectedHeader(token).kid;
  } catch {
    throw unauthorised("The access token is malformed.");
  }
  const secret = config.tokenSecrets.find((candidate) => candidate.kid === kid);
  if (!secret) throw unauthorised("The access token was signed with an unknown key.");

  try {
    const { payload } = await jwtVerify(token, secret.key, {
      issuer: TOKEN_ISSUER,
      audience: TOKEN_AUDIENCE,
      algorithms: ["HS256"],
      typ: "JWT",
      currentDate: new Date(nowSeconds * 1000),
      clockTolerance: CLOCK_TOLERANCE_SECONDS,
      requiredClaims: ["sub", "exp", "iat", "jti"],
    });
    const scopes = String(payload.scope ?? "")
      .split(" ")
      .filter((value): value is ApiScope => (API_SCOPES as readonly string[]).includes(value));
    return {
      sub: String(payload.sub),
      scopes,
      platform: typeof payload.pf === "string" ? payload.pf.slice(0, 16) : "unknown",
      iat: Number(payload.iat),
      exp: Number(payload.exp),
      jti: String(payload.jti),
    };
  } catch (error) {
    if (error instanceof joseErrors.JWTExpired) throw unauthorised("The access token has expired; register the device again.", "token_expired");
    throw unauthorised("The access token is not valid.");
  }
}
